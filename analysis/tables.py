"""Markdown tables for the report, built only from results/*.csv, so no number is typed by hand.

    python analysis/tables.py      # writes report/tables.md
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
ORDER = ["MiniCPM5-2B", "K2 Horizon 3.7B", "Qwen3.5-4B", "K2 Horizon 7B"]
MODE = {"think": "on", "nothink": "off / low"}


def pct(x, d=1):
    return "–" if pd.isna(x) else f"{100 * x:.{d}f}"


def rng(r, k, d=1, scale=100):
    if pd.isna(r[k]):
        return "–"
    return f"{scale * r[k]:.{d}f} [{scale * r[k + '_lo']:.{d}f}, {scale * r[k + '_hi']:.{d}f}]"


def sort(df):
    df = df.copy()
    df["_o"] = df["model"].map({m: i for i, m in enumerate(ORDER)})
    df["_m"] = df["mode"].map({"think": 0, "nothink": 1})
    return df.sort_values(["_o", "_m"])


def calibration():
    c = sort(pd.read_csv(R / "summary_calibration.csv"))
    lines = ["| Model | Thinking | Accuracy % | Mean confidence % | Overconfidence (points) | Brier | Brier skill vs constant | AUROC | Right when ≥90% sure |",
             "|---|---|---|---|---|---|---|---|---|"]
    for _, r in c.iterrows():
        lines.append(f"| {r['model']} | {MODE[r['mode']]} | {rng(r, 'accuracy')} | {pct(r['mean_confidence'])} | "
                     f"{rng(r, 'overconfidence')} | {rng(r, 'brier', 3, 1)} | {r['brier_skill_vs_constant']:.2f} | "
                     f"{rng(r, 'auroc', 2, 1)} | {pct(r['accuracy_when_conf_ge90'])} ({pct(r['share_conf_ge90'], 0)}% of answers) |")
    return "\n".join(lines)


def abstention():
    a = sort(pd.read_csv(R / "summary_abstention.csv"))
    lines = ["| Model | Thinking | Prompt | Abstain, unanswerable % | of which invented entities % | Abstain, answerable % | Abstain on known answers % | Wrong on answerable % | Penalty score (+1/−3/0) |",
             "|---|---|---|---|---|---|---|---|---|"]
    for _, r in a.sort_values(["_o", "_m", "condition"], ascending=[True, True, False]).iterrows():
        lines.append(f"| {r['model']} | {MODE[r['mode']]} | {r['condition']} | {rng(r, 'unanswerable_abstain', 0)} | "
                     f"{pct(r['fabricated_abstain'], 0)} | {rng(r, 'answerable_abstain', 0)} | {pct(r['abstain_on_known'], 0)} | "
                     f"{pct(r['answerable_wrong'], 0)} | {r['penalty_score']:+.2f} [{r['penalty_score_lo']:+.2f}, {r['penalty_score_hi']:+.2f}] |")
    return "\n".join(lines)


def pushback():
    p = R / "summary_pushback.csv"
    if not p.exists():
        return "(pending)"
    s = sort(pd.read_csv(p))
    lines = ["| Model | Thinking | Started right (n) | Right → wrong after “are you sure?” % | Right → wrong by end % | Gave up answers stated ≥95% | Gave up answers stated <95% | Started wrong (n) | Wrong → right by end % | Confidence predicts giving in (AUROC) |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in s.iterrows():
        lines.append(f"| {r['model']} | {MODE[r['mode']]} | {int(r['n_start_right'])} | {pct(r['right_to_wrong_by_step0'])} | "
                     f"{rng(r, 'right_to_wrong_end', 0)} | {pct(r['cave_rate_conf_ge95'], 0)}% of {int(r['n_conf_ge95'])} | "
                     f"{pct(r['cave_rate_conf_lt95'], 0)}% of {int(r['n_conf_lt95'])} | {int(r['n_start_wrong'])} | "
                     f"{rng(r, 'wrong_to_right_end', 0)} | {rng(r, 'conf_predicts_caving', 2, 1)} |")
    return "\n".join(lines)


def paired():
    d = pd.read_csv(R / "paired_differences.csv")
    lines = ["| Comparison | Model | Thinking | Measure | Difference [95% CI] |", "|---|---|---|---|---|"]
    for _, r in d.iterrows():
        sc = 1 if "score" in r["metric"] or r["metric"] == "brier" else 100
        dd = 3 if r["metric"] == "brier" else (2 if sc == 1 else 1)
        mode = MODE.get(r["mode"], "") if isinstance(r["mode"], str) else ""
        star = " *" if r["excludes_zero"] else ""
        lines.append(f"| {r['comparison']} | {r['model']} | {mode} | {r['metric']} | "
                     f"{sc * r['diff']:+.{dd}f} [{sc * r['lo']:+.{dd}f}, {sc * r['hi']:+.{dd}f}]{star} |")
    return "\n".join(lines)


def main():
    out = ["# Report tables (generated by analysis/tables.py)", "",
           "Intervals are 95% bootstrap over questions. Overconfidence = mean stated confidence minus accuracy, parsed replies.",
           "Brier skill vs constant = 1 − Brier / (acc × (1 − acc)): how much better than always stating the model's own accuracy.",
           "", "## Table 1. Calibration (200 questions × 3 runs)", "", calibration(),
           "", "## Table 2. Abstention (50 unanswerable + 50 answerable × 3 runs)", "", abstention(),
           "", "## Table 3. Pushback (run 1 answers)", "", pushback(),
           "", "## Table 4. Paired differences (* = interval excludes zero)", "", paired(), ""]
    (ROOT / "report" / "tables.md").write_text("\n".join(out))
    print("wrote report/tables.md")


if __name__ == "__main__":
    main()
